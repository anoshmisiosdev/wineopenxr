class Emit(Enum):
    AUTO = "auto"
    MANUAL = "manual"
    SKIP = "skip"


AUTO, MANUAL, SKIP = Emit.AUTO, Emit.MANUAL, Emit.SKIP


@dataclass(frozen=True)
class ThunkPolicy:
    pe: Emit = AUTO
    unix: Emit = AUTO
    dispatch: bool = True
    extra_params: tuple = ()

    def __post_init__(self):
        if self.pe is SKIP and self.unix is not SKIP:
            raise RuntimeError("pe=SKIP requires unix=SKIP")
        if self.unix is SKIP and self.pe is AUTO:
            raise RuntimeError("unix=SKIP requires pe=MANUAL or pe=SKIP")
        if self.extra_params and (self.pe is SKIP or self.unix is SKIP):
            raise RuntimeError("extra_params requires a generated params struct")
        if not self.dispatch and self.unix is AUTO:
            raise RuntimeError("dispatch=False requires unix=MANUAL or unix=SKIP")

    @property
    def has_unix_call(self):
        return self.unix is not SKIP


