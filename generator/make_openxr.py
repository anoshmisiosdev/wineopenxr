@dataclass(frozen=True)
class XrParameter:
    type_name: str
    name: str
    is_const: bool
    is_struct: bool
    pointer: str
    is_array: bool

    @classmethod
    def from_xml(cls, element):
        type_element = element.find("type")
        name_element = element.find("name")
        return cls(type_name=type_element.text,
                   name=name_element.text,
                   is_const=bool(element.text and "const" in element.text),
                   is_struct=bool(element.text and "struct" in element.text),
                   pointer=(type_element.tail or "").strip(),
                   is_array=(name_element.tail or "").strip().startswith("["))

    @property
    def is_wrapped_handle(self):
        return self.type_name in WRAPPED_HANDLES and not self.pointer

    def c_type(self):
        parts = []
        if self.is_const:
            parts.append("const")
        if self.is_struct:
            parts.append("struct")
        parts.append(self.type_name)
        if self.pointer:
            parts.append(self.pointer)
        declaration = " ".join(parts)
        if self.is_array:
            declaration += " *"
        return declaration

    def struct_field(self):
        return f"    {self.c_type()} {self.name};"

    def unix_call_argument(self):
        if self.is_wrapped_handle:
            accessor, host_field = WRAPPED_HANDLES[self.type_name]
            return f"{accessor}(params->{self.name})->{host_field}"
        return f"params->{self.name}"


@dataclass
class XrCommand:
    name: str
    return_type: str
    parameters: list
    alias_target: str = None

    @classmethod
    def from_xml(cls, element):
        prototype = element.find("proto")
        return cls(prototype.find("name").text, prototype.find("type").text,
                   [XrParameter.from_xml(parameter) for parameter in element.findall("param")])

    def aliased_as(self, alias_name):
        return XrCommand(alias_name, self.return_type, self.parameters,
                         alias_target=self.name)


@dataclass
class Registry:
    commands: dict
    types: dict
    extensions: dict
    command_extension: dict
    command_core_minor: dict
    event_structs: list

    @classmethod
    def from_xml(cls, xml_path):
        root = ET.parse(xml_path).getroot()

        types = {}
        for type_element in root.findall("./types/type"):
            name = type_element.get("name") or type_element.find("name").text
            members = []
            structure_type = None
            if type_element.get("category") in ("struct", "union") and not type_element.get("alias"):
                for member in type_element.findall("member"):
                    member_type = member.find("type")
                    member_name = member.find("name")
                    members.append((member_type.text, member_name.text))
                    if member_name.text == "type" and member.get("values"):
                        structure_type = member.get("values")
            structextends = type_element.get("structextends")
            types[name] = {
                "category": type_element.get("category"),
                "requires": type_element.get("requires"),
                "alias": type_element.get("alias"),
                "members": members,
                "parentstruct": type_element.get("parentstruct"),
                "structextends": structextends.split(",") if structextends else [],
                "structure_type": structure_type,
            }

        commands = {}
        deferred_aliases = []
        for command_element in root.findall("./commands/command"):
            alias_target = command_element.get("alias")
            if alias_target:
                deferred_aliases.append((command_element.get("name"), alias_target))
                continue
            command = XrCommand.from_xml(command_element)
            commands[command.name] = command
        for alias_name, target_name in deferred_aliases:
            commands[alias_name] = commands[target_name].aliased_as(alias_name)

        command_core_minor = {}
        for feature in root.findall("feature"):
            minor = REGISTRY_CORE_FEATURES.get(feature.get("name"))
            if minor is None:
                continue
            for require in feature.findall("require"):
                for command in require.findall("command"):
                    command_core_minor[command.get("name")] = minor

        extensions = {}
        command_extension = {}
        for extension in root.findall(".//extensions/extension"):
            if "openxr" not in extension.get("supported", "").split(","):
                continue
            extension_name = extension.get("name")
            command_names = {command.get("name")
                             for require in extension.findall("require")
                             for command in require.findall("command")}
            type_names = {type_element.get("name")
                          for require in extension.findall("require")
                          for type_element in require.findall("type")}
            conditional_requires = [require.get("depends")
                                    for require in extension.findall("require")
                                    if require.get("depends")]
            extensions[extension_name] = {
                "guard": extension.get("protect"),
                "depends": extension.get("depends"),
                "commands": command_names,
                "types": type_names,
                "conditional_requires": conditional_requires,
            }
            for command_name in command_names:
                command_extension.setdefault(command_name, set()).add(extension_name)

        event_structs = []
        for name in sorted(types):
            information = types[name]
            if information["parentstruct"] != EVENT_BASE_STRUCT:
                continue
            for member_type, member_name in information["members"]:
                if member_type in WRAPPED_HANDLES:
                    event_structs.append((name, member_name, member_type))

        return cls(commands=commands, types=types,
                   extensions=extensions, command_extension=command_extension,
                   command_core_minor=command_core_minor, event_structs=event_structs)

    def type_closure(self, root_type_names):
        seen = set()
        stack = list(root_type_names)
        while stack:
            type_name = stack.pop()
            if type_name in seen:
                continue
            seen.add(type_name)
            information = self.types[type_name]
            if information["alias"]:
                stack.append(information["alias"])
            stack.extend(member_type for member_type, _ in information["members"])
        return seen


def depends_satisfiable(expression, satisfied_names):
    atoms = [""]
    operators = []
    depth = 0
    for character in expression:
        if character == "(":
            depth += 1
        elif character == ")":
            depth -= 1
        if character in "+," and depth == 0:
            operators.append(character)
            atoms.append("")
        else:
            atoms[-1] += character

    def atom_satisfiable(atom):
        atom = atom.strip()
        if atom.startswith("("):
            return depends_satisfiable(atom[1:-1], satisfied_names)
        return atom in satisfied_names

    result = atom_satisfiable(atoms[0])
    for operator, atom in zip(operators, atoms[1:]):
        if operator == "+":
            result = result and atom_satisfiable(atom)
        else:
            result = result or atom_satisfiable(atom)
    return result


def group_by_guard(pairs):
    groups = {guard: [] for guard in (None, *GUARD_ORDER)}
    for name, info in pairs:
        groups[info.guard].append((name, info))
    return groups


def emit_guarded(out, groups, emit_entry, prelude=(), blank_after=False):
    for name, info in groups[None]:
        emit_entry(name, info)
    for guard in GUARD_ORDER:
        entries = groups[guard]
        if not entries:
            continue
        out.append(f"#ifdef {guard}")
        out.extend(prelude)
        for name, info in entries:
            emit_entry(name, info)
        out.append(f"#endif /* {guard} */")
        if blank_after:
            out.append("")


@dataclass
class FunctionInfo:
    command: XrCommand
    policy: ThunkPolicy
    guard: str
    extension: str
    core_minor: int
    is_global: bool


@dataclass
class GenerationPlan:
    generated: dict
    extension_rows: list
    session_events: list
    function_rows: list
    unix_slots: list
    dispatch_groups: dict

    @classmethod
    def from_registry(cls, registry):
        generated = {}
        unix_only = {}

        for name in sorted(registry.commands):
            command = registry.commands[name]
            providing = registry.command_extension.get(name, set())
            if len(providing) > 1:
                raise RuntimeError(f"{name} is provided by multiple extensions: "
                                   f"{', '.join(sorted(providing))}")
            extension = next(iter(providing)) if providing else None
            is_core = name in registry.command_core_minor
            if not is_core and extension not in SUPPORTED_EXTENSIONS and name not in FUNCTION_POLICIES:
                continue
            guard = registry.extensions[extension]["guard"] if extension else None
            policy = FUNCTION_POLICIES.get(name, ThunkPolicy())

            info = FunctionInfo(command=command, policy=policy, guard=guard,
                                extension=extension,
                                core_minor=registry.command_core_minor.get(name, 0),
                                is_global=name in GLOBAL_FUNCTIONS)

            if policy.pe is SKIP:
                unix_only[name] = info
                continue
            generated[name] = info

        for name in FUNCTION_POLICIES:
            if name not in generated and name not in unix_only:
                raise RuntimeError(f"FUNCTION_POLICIES entry {name!r} does not match any generated command")

        for name, info in generated.items():
            if info.extension and info.extension not in SUPPORTED_EXTENSIONS:
                raise RuntimeError(f"{name} is provided by {info.extension}, "
                                   f"which is not in SUPPORTED_EXTENSIONS")
            if info.policy.has_unix_call:
                violation = boundary_violation(registry, info.command, info.guard)
                if violation:
                    raise RuntimeError(f"{name} cannot cross the PE/Unix boundary: {violation}")
            if info.command.alias_target:
                target = info.command.alias_target
                if ((target in generated or target in unix_only)
                        and (name in FUNCTION_POLICIES) != (target in FUNCTION_POLICIES)):
                    raise RuntimeError(f"FUNCTION_POLICIES covers only one of alias {name!r} "
                                       f"and target {target!r}")

        for extension_name in sorted(SUPPORTED_EXTENSIONS):
            if extension_name not in registry.extensions:
                raise RuntimeError(f"SUPPORTED_EXTENSIONS references unknown extension {extension_name!r}")
            for command_name in sorted(registry.extensions[extension_name]["commands"]):
                if command_name not in generated:
                    raise RuntimeError(f"{extension_name} is supported but {command_name} is not generated")
            depends = registry.extensions[extension_name]["depends"]
            if depends:
                satisfied = set(SUPPORTED_EXTENSIONS) | set(REGISTRY_CORE_FEATURES)
                if not depends_satisfiable(depends, satisfied):
                    raise RuntimeError(f"{extension_name} dependencies not satisfiable "
                                       f"from SUPPORTED_EXTENSIONS: {depends}")
            conditional_requires = registry.extensions[extension_name]["conditional_requires"]
            if conditional_requires:
                raise RuntimeError(f"{extension_name} has conditional require blocks "
                                   f"the generator does not evaluate: "
                                   f"{', '.join(conditional_requires)}")
            for type_name in sorted(registry.extensions[extension_name]["types"]):
                information = registry.types.get(type_name)
                if not information:
                    continue
                for chain_target in sorted(STRIPPED_NEXT_CHAINS):
                    if chain_target in information["structextends"]:
                        raise RuntimeError(f"{extension_name} chains {type_name} onto "
                                           f"{chain_target}, which the bridge does not forward")

        extension_rows = sorted(SUPPORTED_EXTENSIONS)
        extension_index = {name: index for index, name in enumerate(extension_rows)}

        session_events = []
        for struct_name, member_name, member_type in registry.event_structs:
            owners = {extension_name for extension_name, information in registry.extensions.items()
                      if struct_name in information["types"]}
            if owners and not owners & SUPPORTED_EXTENSIONS:
                continue
            if member_type != "XrSession":
                raise RuntimeError(f"cannot rewrite {member_type} handle in event {struct_name}")
            structure_type = registry.types[struct_name]["structure_type"]
            session_events.append((structure_type, struct_name, member_name))

        function_rows = []
        for name, info in generated.items():
            if info.policy.pe is MANUAL:
                pfn = f"(void *){name}"
            else:
                pfn = f"(void *)wine_{name}"
            if info.extension:
                extension_field = extension_index[info.extension]
                core_minor = 0
            else:
                extension_field = -1
                core_minor = info.core_minor
            function_rows.append((name, pfn, extension_field, core_minor,
                                  1 if info.is_global else 0))
        function_rows.sort(key=lambda row: row[0])

        unix_slots = [("init", "wine_init")]
        unix_slots += [(name, f"wine_{name}") for name in CUSTOM_UNIX_CALLS]
        for name, info in generated.items():
            if not info.policy.has_unix_call:
                continue
            handler = f"wine_{name}" if info.policy.unix is MANUAL else f"thunk_{name}"
            unix_slots.append((name, handler))

        dispatch_groups = group_by_guard((name, info)
                                         for source in (generated, unix_only)
                                         for name, info in source.items()
                                         if info.policy.dispatch)

        return cls(generated=generated,
                   extension_rows=extension_rows,
                   session_events=session_events,
                   function_rows=function_rows, unix_slots=unix_slots,
                   dispatch_groups=dispatch_groups)


def boundary_violation(registry, command, guard):
    if guard not in PE_GUARDS:
        return f"platform guard {guard}"
    closure = registry.type_closure(parameter.type_name for parameter in command.parameters)
    for type_name in sorted(closure):
        information = registry.types[type_name]
        if type_name in UNSUPPORTED_TYPES:
            return f"unsupported type {type_name}"
        if information["category"] == "funcpointer":
            return f"function pointer {type_name}"
        requires = information["requires"]
        if requires and requires not in REGISTRY_SUPPORTED_REQUIRES:
            return f"{type_name} requires {requires}"
    return None


def emit_unixcall_h(plan):
    out = [GENERATED_BANNER]
    out.append("#ifndef __WINE_OPENXR_UNIXCALL_H")
    out.append("#define __WINE_OPENXR_UNIXCALL_H")
    out.append("")
    out.append('#include "openxr/openxr.h"')
    out.append("#include <stdint.h>")
    out.append("")
    out.append("#if !defined(_WINNT_) && !defined(__WINE_WINTERNL_H)")
    out.append("typedef int32_t NTSTATUS;")
    out.append("#endif")
    out.append("")

    out.append("enum unix_call")
    out.append("{")
    for suffix, _handler in plan.unix_slots:
        out.append(f"    unix_{suffix},")
    out.append("    unix_count,")
    out.append("};")
    out.append("")
    out.append(f"#define XR_BRIDGE_EXTENSION_COUNT {len(plan.extension_rows)}")
    out.append("")

    def emit_params(name, info):
        out.append(f"struct {name}_params")
        out.append("{")
        for parameter in info.command.parameters:
            out.append(parameter.struct_field())
        out.append("    XrResult result;")
        for extra_field in info.policy.extra_params:
            out.append(f"    {extra_field}")
        out.append("};")
        out.append("")

    unix_call_groups = group_by_guard((name, info)
                                      for name, info in plan.generated.items()
                                      if info.policy.has_unix_call)
    emit_guarded(out, unix_call_groups, emit_params,
                 prelude=('#include "openxr/openxr_platform.h"', ""),
                 blank_after=True)

    out.append("#endif /* __WINE_OPENXR_UNIXCALL_H */")
    return "\n".join(out) + "\n"


def emit_dispatch_h(plan):
    out = [GENERATED_BANNER]
    out.append("#ifndef __WINE_OPENXR_DISPATCH_H")
    out.append("#define __WINE_OPENXR_DISPATCH_H")
    out.append("")
    out.append("#include <stddef.h>")
    out.append("")

    def slot_line(name, info):
        parameter_types = ", ".join(parameter.c_type()
                                    for parameter in info.command.parameters)
        return f"    {info.command.return_type} (*p_{name})({parameter_types});"

    out.append("struct openxr_instance_funcs")
    out.append("{")
    emit_guarded(out, plan.dispatch_groups,
                 lambda name, info: out.append(slot_line(name, info)))
    out.append("};")
    out.append("")

    out.append("struct openxr_instance_function")
    out.append("{")
    out.append("    const char *name;")
    out.append("    size_t offset;")
    out.append("    const char *extension;")
    out.append("};")
    out.append("")
    out.append("extern const struct openxr_instance_function openxr_instance_functions[];")
    out.append("extern const unsigned int openxr_instance_function_count;")
    out.append("")

    out.append("#endif /* __WINE_OPENXR_DISPATCH_H */")
    return "\n".join(out) + "\n"


